"""Detector 3: HTML comments that carry instructions or bulk hidden text."""

from __future__ import annotations

import re

from bs4.element import Comment

from .base import Detector, Finding, Page, Severity, clip, describe, register
from .patterns import find_instruction

CONDITIONAL = re.compile(r"^\[(?:if|endif)\b|^<!\[endif", re.IGNORECASE)
BOILERPLATE = re.compile(
    r"licen[cs]e|copyright|@preserve|generated by|saved from url|google tag manager"
    r"|end of |begin ",
    re.IGNORECASE,
)
LONG_COMMENT = 100


@register
class HtmlComments(Detector):
    name = "html_comments"
    description = "HTML comments that contain instructions or large amounts of hidden text"

    def scan(self, page: Page) -> list[Finding]:
        findings: list[Finding] = []

        for node in page.soup.find_all(string=lambda s: isinstance(s, Comment)):
            text = str(node).strip()
            if not text or CONDITIONAL.match(text):
                continue

            location = f"comment in {describe(node.parent)}" if node.parent else "comment"

            phrase = find_instruction(text)
            if phrase:
                findings.append(
                    Finding(
                        detector=self.name,
                        severity=Severity.HIGH,
                        message=f'Comment contains instruction-like text: "{clip(phrase, 60)}"',
                        location=location,
                        snippet=clip(text),
                    )
                )
                continue

            is_long = len(text) >= LONG_COMMENT
            if is_long and not text.startswith("<") and not BOILERPLATE.search(text):
                findings.append(
                    Finding(
                        detector=self.name,
                        severity=Severity.LOW,
                        message="Long comment not shown to readers",
                        location=location,
                        snippet=clip(text),
                    )
                )

        return findings